// T539: a copy of this repository in a scratch git repository, with origin/main, so that the real build and check run on
// branches as they do on a pull request. Git runs with no shell; test-env.mjs keeps the developer's git config out.
function fixture(t) {
  const dir = mkdtempSync(join(realpathSync(tmpdir()), "sage-changelog-repo-"));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  cpSync(ROOT, dir, { recursive: true, filter: (src) => ![".git", ".claude", "node_modules"].includes(relative(ROOT, src)) });
  const git = (...args) => spawnSync("git", ["-c", "user.name=t", "-c", "user.email=t@example.com", "-c", "init.defaultBranch=main", ...args], { cwd: dir, encoding: "utf8", env: { ...process.env, HOME: dir } });
  const run = (script) => spawnSync("node", [join(dir, "scripts", script)], { cwd: dir, encoding: "utf8" });
  git("init", "-q");
  symlinkSync(join(ROOT, "node_modules"), join(dir, "node_modules"), "dir");
  writeFileSync(join(dir, ".git/info/exclude"), "node_modules\n");
  /** Commit on branch (made from `from` when it does not exist yet), with these files written and, if given, scripts run. */
  const commit = (branch, from, files = {}, scripts = []) => {
    assert.equal(git("checkout", "-q", ...(git("rev-parse", "-q", "--verify", branch).status ? ["-b", branch, from] : [branch])).status, 0);
    for (const [path, text] of Object.entries(files)) writeFileSync(join(dir, path), text);
    for (const script of scripts) assert.equal(run(script).status, 0, script);
    assert.equal(git("add", "-A").status, 0);
    assert.equal(git("commit", "-qm", branch, "--allow-empty").status, 0);
  };
  assert.equal(git("add", "-A").status, 0);
  assert.equal(git("commit", "-qm", "main").status, 0);
  const publish = () => assert.equal(git("update-ref", "refs/remotes/origin/main", "main").status, 0); // as git fetch does
  publish();
  return { dir, git, run, commit, publish };
}
const LAG = /^! CHANGELOG\.md lags behind changes\/ \(allowed on main and on a task branch\); the chief rebuilds it with npm run changelog in a change-log pull request$/m;
const T1 = entry("2099-01-01", "- **First change.** From branch a."), T2 = entry("2099-01-01", "- **Second change.** From branch b.");

test("two task branches from one main, each with its own fragment and npm run build, merge with no conflict, and the check passes on each", (t) => {
  const { git, run, commit } = fixture(t);
  commit("a", "main", { "changes/T99991.md": T1 }, ["build.mjs"]);
  commit("b", "main", { "changes/T99992.md": T2 }, ["build.mjs"]);
  const merged = git("merge-tree", "--write-tree", "--name-only", "--no-messages", "a", "b");
  assert.equal(merged.status, 0, `conflict in: ${merged.stdout.trim().split("\n").slice(1).join(", ")}`);
  assert.deepEqual(git("diff", "--name-only", "main", "b").stdout.split("\n").filter(Boolean), ["changes/T99992.md"], "the build writes no CHANGELOG.md");
  const b = run("check.mjs");
  assert.equal(b.status, 0, b.stderr);
  assert.match(b.stderr, LAG, "a task branch with a fragment and the CHANGELOG.md of main passes, with a warning");
  assert.equal(git("merge", "-q", "--no-edit", "a").status, 0);
  const both = run("check.mjs");
  assert.equal(both.status, 0, both.stderr);
});

const refusal = (base) => `✗ CHANGELOG.md: a task pull request carries only its changes/<task>.md and leaves CHANGELOG.md as main has it; put your text in changes/<task>.md and undo the edit of CHANGELOG.md (git fetch origin main, then git checkout ${base} -- CHANGELOG.md). The chief rebuilds it on main with npm run changelog, in a change-log pull request that changes only CHANGELOG.md`;

test("a task branch whose diff edits CHANGELOG.md fails the check, committed or not, and passes when the edit is undone", (t) => {
  const { dir, git, run, commit } = fixture(t);
  commit("a", "main", { "changes/T99991.md": T1 }, ["changelog.mjs"]);
  const base = git("rev-parse", "main").stdout.trim();
  const refused = refusal(base);
  const committed = run("check.mjs");
  assert.equal(committed.status, 1);
  assert.ok(committed.stderr.split("\n").includes(refused), committed.stderr);
  assert.equal(git("checkout", "-q", base, "--", "CHANGELOG.md").status, 0);
  assert.equal(run("check.mjs").status, 0);
  writeFileSync(join(dir, "CHANGELOG.md"), `${readFileSync(join(dir, "CHANGELOG.md"), "utf8")}\n`);
  const edited = run("check.mjs");
  assert.equal(edited.status, 1, "an edit that is not committed yet also counts");
  assert.ok(edited.stderr.split("\n").includes(refused), edited.stderr);
});

test("a change-log branch must hold exactly the build of changes/; main may lag behind with a warning only", (t) => {
  const { git, run, commit, publish, dir } = fixture(t);
  commit("main", "main", { "changes/T99991.md": T1, "changes/T99992.md": T2 });
  publish();
  const lagging = run("check.mjs");
  assert.equal(lagging.status, 0, lagging.stderr);
  assert.match(lagging.stderr, LAG, "main after a merge: CHANGELOG.md lags, and the check passes");
  // A change-log branch with a build that is one fragment short (made before T99992 merged).
  assert.equal(git("checkout", "-q", "-b", "sage/changelog-2099-01-01", "main").status, 0);
  rmSync(join(dir, "changes/T99992.md"));
  assert.equal(run("changelog.mjs").status, 0);
  assert.equal(git("checkout", "-q", "main", "--", "changes/T99992.md").status, 0);
  assert.deepEqual(git("diff", "--name-only", "main").stdout.split("\n").filter(Boolean), ["CHANGELOG.md"]);
  const short = run("check.mjs");
  assert.equal(short.status, 1);
  assert.match(short.stderr, /^✗ CHANGELOG\.md: a change-log pull request holds exactly the build of changes\/; run npm run changelog$/m);
  assert.equal(run("changelog.mjs").status, 0);
  const exact = run("check.mjs");
  assert.equal(exact.status, 0, exact.stderr);
  assert.doesNotMatch(exact.stderr, LAG);
  assert.match(readFileSync(join(dir, "CHANGELOG.md"), "utf8"), /\n## 2099-01-01\n\n- \*\*Second change\.\*\* From branch b\.\n- \*\*First change\.\*\* From branch a\.\n/);
});

