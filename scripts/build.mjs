export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const GENERATED = "<!-- Generated by scripts/build.mjs from the sources; edit the source, then run npm run build. -->";

export function assertSdkBundleGraph(metafile, readSource = file => readFileSync(resolve(ROOT, file), "utf8")) {
  const excluded = /(?:embeddedAjv|ajvProvider|require_fast_uri|require_ajv|(?:^|[/\\])(?:ajv(?:-formats)?|fast-uri|fast-deep-equal|json-schema-traverse)(?:[@/\\.]|$))/i;
  for (const file of Object.keys(metafile.inputs)) {
    if (excluded.test(file) || excluded.test(readSource(file))) {
      throw new Error("Sage SDK bundle includes an excluded JSON Schema validator dependency.");
    }
  }
}

export function parseSource(text, file) {
  const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text);
  if (!m) throw new Error(`${file}: no frontmatter`);
  const meta = {};
  for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    if (i < 1) throw new Error(`${file}: bad frontmatter line "${line}"`);
    meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return { meta, body: m[2].trim() };
}

const q = (s) => JSON.stringify(s);
const skill = (name, description, source, body) =>
  `---\nname: ${name}\ndescription: ${q(description)}\nlicense: MIT\nmetadata:\n  source: ${q(source)}\n---\n\n${GENERATED}\n\n${body}\n`;

export function outputs() {
  const out = new Map();
  const principles = readdirSync(join(ROOT, "principles")).filter((f) => f.endsWith(".md") && f !== "README.md").sort();
  const ownMeta = [];
  for (const f of principles) {
    const { meta, body } = parseSource(readFileSync(join(ROOT, "principles", f), "utf8"), f);
    const name = `principle-${meta.id}`;
    ownMeta.push(meta);
    out.set(join("plugins/sage/skills", name, "SKILL.md"), skill(name, `${meta.name}. Apply when ${meta.applyWhen}`, meta.source, `# ${meta.name}\n\n${body}`));
  }
  const w = parseSource(readFileSync(join(ROOT, "writing/ste-80.md"), "utf8"), "writing/ste-80.md");
  out.set("plugins/sage/skills/writing-standard/SKILL.md", skill("writing-standard", `${w.meta.name}. Apply to ${w.meta.applyWhen}`, w.meta.source, `# ${w.meta.name}\n\n${w.body}`));
  const r = parseSource(readFileSync(join(ROOT, "writing/readme.md"), "utf8"), "writing/readme.md");
  out.set("plugins/sage/skills/readme-guide/SKILL.md", skill("readme-guide", `${r.meta.name}. Apply when ${r.meta.applyWhen}`, r.meta.source, `# ${r.meta.name}\n\n${r.body}`));
  const m = parseSource(readFileSync(join(ROOT, "writing/presentation.md"), "utf8"), "writing/presentation.md");
  if (!m.body.includes(KINDS_MARK)) throw new Error(`writing/presentation.md has no ${KINDS_MARK}`);
  out.set("plugins/sage/skills/presentation/SKILL.md", skill("presentation", `${m.meta.name}: each kind of message, its parts in order, the pictures, the pages and the message command. Apply to ${m.meta.applyWhen}`, m.meta.source, `# ${m.meta.name}\n\n${m.body.replace(KINDS_MARK, kindsTable())}`));
  const d = parseSource(readFileSync(join(ROOT, "writing/dictionary.md"), "utf8"), "writing/dictionary.md");
  checkWords(d.body);
  out.set("plugins/sage/skills/dictionary/SKILL.md", skill("dictionary", `${d.meta.name}: sage's approved words, one meaning each, and the words not to say. Apply to ${d.meta.applyWhen}`, d.meta.source, `# ${d.meta.name}\n\n${d.body}`));
  const rows = principleRows(ownMeta);
  out.set(WORDS_PAGE, withWordTable(readFileSync(join(ROOT, WORDS_PAGE), "utf8"), wordTable(d.body)));
  out.set(PRINCIPLES_PAGE, withPrinciplesTable(readFileSync(join(ROOT, PRINCIPLES_PAGE), "utf8"), principlesTable(rows)));
  const p = parseSource(readFileSync(join(ROOT, "preferences/working-preferences.md"), "utf8"), "preferences/working-preferences.md");
  out.set("instructions/core.md", `${GENERATED}\n\n# ${p.meta.name}\n\n${p.body}\n\n# ${w.meta.name}\n\n${w.body}\n`);
  return packageOutputs(out);
}

const KINDS_MARK = "<!-- sage-core-message-kinds -->";
const TYPE_WORDS = { picture: "a picture", table: "a table", toggle: "a toggle", changes: "a change table", steps: "numbered steps", page: "a Page block" };
export function kindsTable() {
  const part = (kind) => (p) => {
    const answers = p.name === "table" && KINDS[kind].pick;
    const name = TYPE_WORDS[p.name] ? `${answers ? "the answers, a numbered list" : TYPE_WORDS[p.name]}${p.name === "table" && KINDS[kind].tableHead ? ` (${KINDS[kind].tableHead.join(", ")}${answers ? "; your pick first" : ""})` : ""}${answers ? "; for a batch, a section of its own for each question" : p.many ? (p.need ? ", one or more" : ", any number") : ""}` : p.name;
    return p.need ? name : `[${name}]`;
  };
  const rows = Object.entries(KINDS).map(([kind, k]) => `| \`${kind}\` | \`${k.head}\` | ${k.use} | ${partsOf(kind).map(part(kind)).join(" · ")} |`);
  return `Each kind: its \`kind\` in the JSON, its head (the first line), when to send it, and its parts in order after the title. A part in [brackets] is optional; a paragraph may stand anywhere. The last part of the text is the Ref line, when the message has ids to give.\n\n| Kind | Head | When | Parts, in order |\n| --- | --- | --- | --- |\n${rows.join("\n")}`;
}

export function filesUnder(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name)).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`package contains a symbolic link: ${path}`);
    return entry.isDirectory() ? filesUnder(path) : [path];
  });
}

function packageOutputs(generated) {
  const out = new Map([...generated].filter(([path]) => !path.startsWith("plugins/")));
  const core = JSON.parse(readFileSync(join(ROOT, "packages/sage-core/package.json"), "utf8"));
  const sharedSkills = [...generated].filter(([path]) => path.startsWith("plugins/sage/skills/"));
  const app = buildBoardApp(ROOT), markdown = buildBoardMarkdown(ROOT);
  for (const [provider, target] of [["claude", "plugins/sage"], ["codex", "plugins/sage-codex"]]) {
    const source = join(ROOT, `packages/sage-${provider}`);
    const meta = JSON.parse(readFileSync(join(source, "package.json"), "utf8"));
    if (meta.dependencies?.[core.name] !== core.version) throw new Error(`${meta.name} must pin ${core.name} ${core.version}`);
    for (const file of filesUnder(source)) {
      const rel = relative(source, file);
      if (rel === "package.json") continue;
      const specifier = relative(dirname(rel), "core/index.mjs").replaceAll("\\", "/");
      let text = readFileSync(file, "utf8");
      if (text.includes("<!-- sage-core-chief -->")) {
        const bindings = JSON.parse(readFileSync(join(source, "chief-bindings.json"), "utf8"));
        text = text.replaceAll("<!-- sage-core-chief -->", renderChiefInstructions(bindings));
      }
      if (/<!-- sage-core-(?:role: |report)/.test(text)) {
        const bindings = JSON.parse(readFileSync(join(source, "role-bindings.json"), "utf8"));
        text = text.replace(/<!-- sage-core-role: ([a-z-]+) -->/g, (_, role) => renderRoleInstructions(role, { ...bindings.common, ...bindings[role] }))
          .replace(/<!-- sage-core-report -->/g, () => renderReportInstructions(bindings.report));
      }
      if (provider === "codex" && rel === "runtime/mcp-sdk.mjs") {
        const result = buildSync({
          absWorkingDir: ROOT, entryPoints: [relative(ROOT, file)], bundle: true,
          platform: "node", target: "node20", format: "esm", write: false,
          minify: true, legalComments: "eof", logLevel: "silent",
          metafile: true,
          alias: { "@modelcontextprotocol/server/_shims": "./packages/sage-codex/runtime/sdk-shims.mjs" },
        });
        assertSdkBundleGraph(result.metafile);
        out.set(join(target, rel), result.outputFiles[0].text);
        continue;
      }
      const content = rel.endsWith(".mjs") ? rewriteCoreImports(text, specifier.startsWith(".") ? specifier : `./${specifier}`) : text;
      out.set(join(target, rel), content);
    }
    for (const file of filesUnder(join(ROOT, "packages/sage-core"))) {
      const rel = relative(join(ROOT, "packages/sage-core"), file);
      out.set(join(target, "core", rel), readFileSync(file, "utf8"));
    }
    for (const file of filesUnder(join(ROOT, "packages/sage-board")).filter((path) => path.endsWith(".mjs"))) {
      const rel = relative(join(ROOT, "packages/sage-board"), file);
      out.set(join(target, "board", rel), rel === "markdown.mjs" ? markdown.text : rewriteCoreImports(readFileSync(file, "utf8"), "../core/index.mjs"));
    }
    for (const [name, text] of markdown.licences) out.set(join(target, "licenses", name), text);
    for (const [name, text] of app.files) out.set(join(target, "board", "app", name), text);
    for (const [name, text] of app.licences) out.set(join(target, "licenses", name), text);
    for (const [path, text] of sharedSkills) out.set(path.replace("plugins/sage", target), text);
    if (provider === "codex") {
      const dependencies = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")).devDependencies;
      for (const name of ["@modelcontextprotocol/server", "@modelcontextprotocol/core", "zod", "content-type"]) {
        const dir = join(ROOT, "node_modules", name);
        const installed = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
        const expected = dependencies[name === "@modelcontextprotocol/core" ? "@modelcontextprotocol/server" : name];
        if (installed.version !== expected) throw new Error(`${name} must match the pinned build dependency`);
        out.set(join(target, "licenses", `${name.replaceAll("/", "-")}.txt`),
          `${name} ${installed.version}\n\n${readFileSync(join(dir, "LICENSE"), "utf8")}`);
      }
    }
    out.set(join(target, "LICENSE"), readFileSync(join(ROOT, "LICENSE"), "utf8"));
    out.set(join(target, "LICENSE-pstack"), readFileSync(join(ROOT, "principles/LICENSE-pstack"), "utf8"));
    out.set(join(target, "build.json"), JSON.stringify({ package: meta.name, version: meta.version, core: core.version }, null, 2) + "\n");
  }
  return out;
}

function removeEmptyDirectories(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) if (entry.isDirectory()) removeEmptyDirectories(join(dir, entry.name));
  if (!readdirSync(dir).length) rmdirSync(dir);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  let built;
  try { built = outputs(); } catch (e) { console.error(`✗ ${e.message}`); process.exit(1); }
  for (const [rel, text] of built) {
    const file = join(ROOT, rel);
    if (existsSync(file) && readFileSync(file, "utf8") === text) continue;
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(`${file}.build`, text);
    renameSync(`${file}.build`, file);
  }
  for (const dir of ["plugins/sage", "plugins/sage-codex"]) {
    for (const file of filesUnder(join(ROOT, dir))) if (!built.has(relative(ROOT, file))) rmSync(file);
    removeEmptyDirectories(join(ROOT, dir));
  }
  console.log(`built ${built.size} files`);
}
